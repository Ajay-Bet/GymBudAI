from tests.conftest import auth_header, iso, make_set_payload, register_user, workout_body

FIXTURES = json.loads((Path(__file__).parent / "fixtures" / "frontend_set_payloads.json").read_text())
COUNTED = ("workout_sessions", "workout_sets", "reps", "form_events", "form_event_reps")


def counts(engine) -> dict[str, int]:
    with engine.connect() as connection:
        return {t: connection.execute(text(f"SELECT count(*) FROM {t}")).scalar_one() for t in COUNTED}


@pytest.fixture
def headers(api):
    return auth_header(register_user(api)["accessToken"])


def save(api, headers, workout, payload):
    """What saveQueue.save does: idempotent create, then submit the set."""
    created = api.post("/api/workouts", json=workout, headers=headers)
    assert created.status_code in (200, 201), created.text
    submitted = api.post(f"/api/workouts/{created.json()['id']}/sets", json=payload, headers=headers)
    return created, submitted


