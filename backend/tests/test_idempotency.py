"""Sprint 5 independent validation (s5-validation): GB 503 reliable saves.

- A simulated timeout (the server committed, the client never saw the answer and retries the same
  create + set) leaves the counts of sessions, sets, reps, form events and links unchanged.
- Concurrent duplicates never create duplicates or 500s.
- A conflicting replay (same clientSetId, different content) is 409 and changes nothing.
- Replays after finalization still answer 200; new sets are 409 `workout-finalized`.
- End to end: payloads built by the REAL frontend chain (tests/fixtures/frontend_set_payloads.json,
  generated by frontend/tests/fixtures/workout-payload-fixtures.js from SYNTHETIC frames) are accepted
  and every summary field round-trips through GET detail.
Runs against the real PostgreSQL test database (TEST_DATABASE_URL).
"""

from __future__ import annotations

