def _workout_for(payload: dict) -> dict:
    return workout_body(started_at=datetime.fromisoformat(payload["startedAt"].replace("Z", "+00:00")))


def _close(a, b) -> bool:
    if isinstance(a, float) or isinstance(b, float):
        return a is not None and b is not None and abs(a - b) < 1e-9
    return a == b


@pytest.mark.parametrize("name", ["validatedOnly", "review"])
def test_frontend_built_payload_round_trips_every_field(api, headers, clean_db, name):
    payload = copy.deepcopy(FIXTURES[name])
    workout = _workout_for(payload)
    created, submitted = save(api, headers, workout, payload)
    assert submitted.status_code == 201, submitted.text
    detail = api.get(f"/api/workouts/{created.json()['id']}", headers=headers).json()
    stored = detail["sets"][0]
    summary = payload["summary"]

    assert "cueLog" not in summary  # the builder already drops it
    assert stored["summary"] == summary, "stored summary differs from the sent summary"
    columns = {
        "clientSetId": payload["clientSetId"], "setIndex": payload["setIndex"], "side": summary["side"],
        "view": summary["view"], "mode": summary["mode"], "summarySchemaVersion": summary["schemaVersion"],
        "analyzerVersion": summary["analyzerVersion"], "featureVersion": summary["featureVersion"],
        "rulesVersion": summary["rulesVersion"], "feedbackVersion": summary["feedbackVersion"],
        "completedReps": summary["completedReps"], "analyzedReps": summary["analyzedReps"],
        "issueBearingReps": summary["issueBearingReps"], "noIssueReps": summary["noIssueReps"],
        "noIssueFraction": summary["noIssueFraction"], "notAnalyzedReason": summary["notAnalyzedReason"],
        "trackingAssessableMs": summary["trackingCoverage"]["assessableMs"],
        "trackingSessionMs": summary["trackingCoverage"]["sessionMs"],
        "trackingCoverage": summary["trackingCoverage"]["fraction"],
        "interruptedAttempts": summary["interruptedAttempts"], "episodeCountsByType": summary["episodeCountsByType"],
    }
    for key, expected in columns.items():
        assert _close(stored[key], expected), (key, stored[key], expected)
    for key in ("startedAt", "endedAt"):
        assert datetime.fromisoformat(stored[key]) == datetime.fromisoformat(payload[key].replace("Z", "+00:00"))
        assert datetime.fromisoformat(stored[key]).utcoffset() == timedelta(0), "stored times must come back as UTC"

    assert [r["clientRepId"] for r in stored["reps"]] == [r["clientRepId"] for r in payload["reps"]]
    for sent, got in zip(payload["reps"], stored["reps"], strict=True):
        for key, value in sent.items():
            assert _close(got[key], value), (key, got[key], value)
    sent_events = {e["clientEventId"]: e for e in payload["formEvents"]}
    assert set(sent_events) == {e["clientEventId"] for e in stored["formEvents"]}
    for got in stored["formEvents"]:
        for key, value in sent_events[got["clientEventId"]].items():
            assert _close(got[key], value), (key, got[key], value)
    # Totals are derived from the stored rows.
    assert detail["totals"] == {"sets": 1, "completedReps": summary["completedReps"],
                                "analyzedReps": summary["analyzedReps"], "issueBearingReps": summary["issueBearingReps"]}
    # And the identical replay is accepted.
    again, replay = save(api, headers, workout, copy.deepcopy(FIXTURES[name]))
    assert (again.status_code, replay.status_code) == (200, 200)
    assert counts(clean_db)["workout_sets"] == 1


