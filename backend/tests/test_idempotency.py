def test_frontend_payload_no_frames_is_rejected_and_leaves_empty_workout(api, headers, clean_db):
    """Finish before any tracked frame: side, view and featureVersion are null in the summary.

    Observed behaviour (reported to the lead): the set is 422 (not retryable), but the workout created
    first by the save queue stays behind as an open workout with 0 sets in the history list.
    """
    payload = copy.deepcopy(FIXTURES["noFrames"])
    assert payload["summary"]["side"] is None and payload["summary"]["view"] is None
    created, submitted = save(api, headers, _workout_for(payload), payload)
    assert submitted.status_code == 422
    body = submitted.text
    for field in ("side", "view", "featureVersion"):
        assert field in body, f"422 should name summary.{field}"
    assert counts(clean_db)["workout_sets"] == 0
    items = api.get("/api/workouts", headers=headers).json()["items"]
    assert [(i["id"], i["totals"]["sets"]) for i in items] == [(created.json()["id"], 0)]
