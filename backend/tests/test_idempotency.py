# Simulated timeout: committed on the server, retried by the client with the same ids and body.
# ---------------------------------------------------------------------------------------------

def test_retry_after_lost_response_changes_no_counts(api, headers, clean_db):
    workout = workout_body()
    payload = make_set_payload(1, 4, mode="review")
    created, submitted = save(api, headers, workout, payload)
    assert (created.status_code, submitted.status_code) == (201, 201)
    after_first = counts(clean_db)
    assert after_first == {"workout_sessions": 1, "workout_sets": 1, "reps": 4, "form_events": 3,
                           "form_event_reps": after_first["form_event_reps"]}
    assert after_first["form_event_reps"] > 0
    first_detail = api.get(f"/api/workouts/{created.json()['id']}", headers=headers).json()

    for _ in range(3):  # the client retries several times (each response "lost")
        again_created, again_submitted = save(api, headers, copy.deepcopy(workout), copy.deepcopy(payload))
        assert again_created.status_code == 200 and again_created.json()["id"] == created.json()["id"]
        assert again_submitted.status_code == 200
        assert again_submitted.json()["id"] == submitted.json()["id"]
        assert counts(clean_db) == after_first
    assert api.get(f"/api/workouts/{created.json()['id']}", headers=headers).json() == first_detail


def test_retry_while_first_request_still_in_flight(make_api, clean_db):
    """The client gives up (timeout) while the server is still working and retries; both requests then
    complete. Modelled by holding the workout row lock in another connection so the first request is
    stuck in the server, sending the retry, then releasing the lock."""
    api_slow, api_retry = make_api(), make_api()
    headers = auth_header(register_user(api_slow)["accessToken"])
    workout = api_slow.post("/api/workouts", json=workout_body(), headers=headers).json()
    payload = make_set_payload(1, 3, mode="review")
    url = f"/api/workouts/{workout['id']}/sets"
    with clean_db.connect() as blocker:
        tx = blocker.begin()
        blocker.execute(text("SELECT id FROM workout_sessions WHERE id = :id FOR UPDATE"), {"id": workout["id"]})
        with ThreadPoolExecutor(2) as pool:
            first = pool.submit(api_slow.post, url, json=payload, headers=headers)
            retry = pool.submit(api_retry.post, url, json=payload, headers=headers)
            threading.Event().wait(0.5)
            assert not first.done() and not retry.done(), "requests should be waiting on the row lock"
            tx.rollback()
            statuses = sorted([first.result(timeout=20).status_code, retry.result(timeout=20).status_code])
    assert statuses == [200, 201]
    c = counts(clean_db)
    assert (c["workout_sets"], c["reps"], c["form_events"]) == (1, 3, 3)


def test_replay_equivalent_encodings_are_identical(api, headers, clean_db):
    """A body re-serialized after a reload (different key order, +00:00 instead of Z) is the same save."""
    workout = workout_body()
    payload = make_set_payload(1, 3, mode="review")
    save(api, headers, workout, payload)
    before = counts(clean_db)
    reordered = json.loads(json.dumps(payload, sort_keys=True))
    reordered = {k: reordered[k] for k in reversed(list(reordered))}
    reordered["summary"] = {k: reordered["summary"][k] for k in reversed(list(reordered["summary"]))}
    reordered["endedAt"] = reordered["endedAt"].replace("Z", "+00:00")
    workout_offset = {**workout, "startedAt": datetime.fromisoformat(workout["startedAt"].replace("Z", "+00:00"))
                      .astimezone(ZoneInfo("America/Chicago")).isoformat()}
    created, submitted = save(api, headers, workout_offset, reordered)
    assert created.status_code == 200
    assert submitted.status_code == 200, submitted.text
    assert counts(clean_db) == before


def test_replay_with_cue_log_changed_is_still_identical(api, headers, clean_db):
    """cueLog is dropped before hashing, so a replay that carries a different cue log is a replay."""
    workout = workout_body()
    payload = make_set_payload(1, 2)
    save(api, headers, workout, payload)
    payload2 = copy.deepcopy(payload)
    payload2["summary"]["cueLog"] = []
