def _parallel(n, fn):
    barrier = threading.Barrier(n)

    def run(i):
        barrier.wait()
        return fn(i)

    with ThreadPoolExecutor(n) as pool:
        return list(pool.map(run, range(n)))


def test_concurrent_duplicate_creates_and_sets(make_api, clean_db):
    clients = [make_api() for _ in range(6)]
    headers = auth_header(register_user(clients[0])["accessToken"])
    workout = workout_body()
    payload = make_set_payload(1, 5, mode="review")

    creates = _parallel(6, lambda i: clients[i].post("/api/workouts", json=workout, headers=headers))
    assert sorted(r.status_code for r in creates) == [200] * 5 + [201], [r.text for r in creates]
    assert len({r.json()["id"] for r in creates}) == 1
    wid = creates[0].json()["id"]

    sets = _parallel(6, lambda i: clients[i].post(f"/api/workouts/{wid}/sets", json=payload, headers=headers))
    assert sorted(r.status_code for r in sets) == [200] * 5 + [201], [r.text for r in sets]
    assert len({r.json()["id"] for r in sets}) == 1
    c = counts(clean_db)
    assert (c["workout_sessions"], c["workout_sets"], c["reps"], c["form_events"]) == (1, 1, 5, 3)


def test_concurrent_conflicting_sets_one_wins_rest_409(make_api, clean_db):
    clients = [make_api() for _ in range(4)]
    headers = auth_header(register_user(clients[0])["accessToken"])
    wid = clients[0].post("/api/workouts", json=workout_body(), headers=headers).json()["id"]
    base = make_set_payload(1, 2, client_set_id="set-race")
    variants = []
    for i in range(4):
        variant = copy.deepcopy(base)
        variant["summary"]["sessionId"] = f"variant-{i}"
        variants.append(variant)
    results = _parallel(4, lambda i: clients[i].post(f"/api/workouts/{wid}/sets", json=variants[i], headers=headers))
    statuses = sorted(r.status_code for r in results)
    assert statuses == [201, 409, 409, 409], [r.text for r in results]
    assert all(r.json()["detail"]["code"] == "conflict" for r in results if r.status_code == 409)
    assert counts(clean_db)["workout_sets"] == 1 and counts(clean_db)["reps"] == 2


def test_concurrent_different_sets_same_index_one_wins(make_api, clean_db):
    clients = [make_api() for _ in range(3)]
    headers = auth_header(register_user(clients[0])["accessToken"])
